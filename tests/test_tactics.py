def test_reject_invalid_configuration_and_input():
    with pytest.raises(ValueError):
        TacticalSolver(Rules(), mode="attacker-only")
    with pytest.raises(ValueError):
        TacticalSolver(Rules(), node_limit=-1)
    with pytest.raises(ValueError):
        TacticalSolver(Rules(), max_depth=-1)
    with pytest.raises(ValueError):
        TacticalSolver(Rules(), time_limit=-1)
    with pytest.raises(ValueError):
        TacticalSolver(Rules()).solve([0], BLACK, 0)
    with pytest.raises(ValueError):
        TacticalSolver(Rules()).solve([0] * 225, 3, 0)
    with pytest.raises(ValueError):
        TacticalSolver(Rules()).solve([0] * 225, BLACK, -1)
