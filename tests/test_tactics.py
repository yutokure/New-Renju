def test_quick_win_opening_and_exact_five_priority():
    rules = Rules()
    cells = [0] * 225
    for col in range(3, 7):
        cells[flat((7, col))] = BLACK
    assert winning_moves(cells, BLACK, 0, rules) == (flat((7, 7)),)
    assert winning_moves(cells, BLACK, 1, rules) == ()
    assert set(winning_moves(cells, BLACK, 3, rules)) == {flat((7, 2)), flat((7, 7))}
    # Black's exact horizontal five takes priority over simultaneous vertical six.
    for row in (4, 5, 6, 8, 9):
        cells[flat((row, 7))] = BLACK
    root = flat((7, 7))
    assert root in winning_moves(cells, BLACK, 20, rules)
    result = TacticalSolver(rules, max_depth=1).verify_root(cells, BLACK, 20, root)
    assert result.status == ProofStatus.PROVEN_WIN and result.pv == (root,)


