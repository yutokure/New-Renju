def test_no_restricted_attack_failure_is_a_loss_and_solver_reuses_cleanly():
    rules = Rules(opening=False)
    solver = TacticalSolver(rules, mode="vct", max_depth=5)
    assert solver.solve([0] * 225, BLACK, 0).status == ProofStatus.UNKNOWN
    cells, root, attacker, count = fixture(BY_ID["vcf-positive-four-three"])
    assert solver.solve(cells, attacker, count, roots=[]).status == ProofStatus.UNKNOWN
    assert solver.solve(cells, attacker, count, roots=[-1, 225, flat((7, 4))]).status == ProofStatus.UNKNOWN
    assert solver.verify_root(cells, attacker, count, root).status == ProofStatus.PROVEN_WIN
    assert solver.solve(cells, attacker, count, roots=[]).status == ProofStatus.UNKNOWN
    # Public LOSS is reserved for an actual terminal opponent win.
    terminal = [0] * 225
    for col in range(3, 8):
        terminal[flat((7, col))] = WHITE
    result = solver.solve(terminal, BLACK, 5)
    assert result.status == ProofStatus.PROVEN_LOSS and result.reason == "already_terminal"
    assert result.move is None and not result.pv
    assert solver.solve(terminal, WHITE, 5).status == ProofStatus.PROVEN_WIN
    for col in range(3, 8):
        terminal[flat((2, col))] = BLACK
    assert solver.solve(terminal, WHITE, 10).status == ProofStatus.UNKNOWN


