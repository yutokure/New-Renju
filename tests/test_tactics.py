def test_quick_wins_never_uses_expensive_rule_classification():
    class GeometryOnlyRules(Rules):
        def classify(self, *args, **kwargs):
            raise AssertionError("quick wins must not classify every empty cell")

        def is_legal(self, *args, **kwargs):
            raise AssertionError("an exact-five win has legality priority")

    rules = GeometryOnlyRules(opening=False)
    cells = [0] * 225
    for col in range(3, 7):
        cells[flat((7, col))] = BLACK
    assert winning_moves(cells, BLACK, 10, rules) == (flat((7, 2)), flat((7, 7)))


def test_remote_defender_black_exact_five_priority_refutes_white_attack():
    cells, root, attacker, count = fixture(BY_ID["vcf-positive-white-forbidden-trap"])
    for col in range(2, 6):
        cells[flat((2, col))] = BLACK
    for row in (0, 1, 3, 4, 5):
        cells[flat((row, 6))] = BLACK
    cells[flat((2, 1))] = WHITE
    count = sum(bool(value) for value in cells)
    rules = Rules(opening=False)
    remote = flat((2, 6))
    verdict = rules.classify(cells, remote, BLACK, count + 1)
    assert verdict.legal and verdict.win  # horizontal five + vertical six
    result = TacticalSolver(rules).verify_root(cells, attacker, count, root)
    assert result.status == ProofStatus.UNKNOWN


