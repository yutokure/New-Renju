def test_own_interruption_is_unknown_and_parent_cancellation_propagates():
    cells, root, attacker, count = fixture(BY_ID["vcf-positive-white-forbidden-trap"])
    original = cells[:]
    calls = 0

    def own_stop():
        nonlocal calls
        calls += 1
        if calls == 90:
            raise TacticalInterrupted("test_deadline")

    result = TacticalSolver(Rules(opening=False), check=own_stop).verify_root(
        cells, attacker, count, root)
    assert result.status == ProofStatus.UNKNOWN and result.reason == "test_deadline"
    assert cells == original

    class ParentSearchStopped(Exception):
        pass

    borrowed_positions = []

    class ObservedRules(Rules):
        def is_legal(self, board, *args, **kwargs):
            borrowed_positions.append(board)
            raise ParentSearchStopped()

    with pytest.raises(ParentSearchStopped):
        TacticalSolver(ObservedRules(opening=False)).verify_root(cells, attacker, count, root)
    assert borrowed_positions and all(board == original for board in borrowed_positions)
    assert cells == original


def test_forcing_helper_restores_on_nested_rule_cancellation():
    case = next(c for c in PROPOSALS["rule_fixtures"]
                if c["id"] == "false-double-three-recursive-extensions")
    cells = [0] * 225
    for row, col in case["black"]:
        cells[flat((row, col))] = BLACK
    original = cells[:]
    original_stones = cells.count(BLACK)

    class Stop(Exception):
        pass

    def check():
        # Interrupt while both a candidate and a recursive hypothetical witness
        # are on the borrowed input, not at a brittle callback-count threshold.
        if cells.count(BLACK) >= original_stones + 2:
            raise Stop()

    with pytest.raises(Stop):
        forcing_moves(cells, BLACK, len(case["black"]), Rules(opening=False), "vct", check)
    assert cells == original


